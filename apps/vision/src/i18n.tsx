type I18nValue = {
  language: VisionLanguage;
  setLanguage: (language: VisionLanguage) => void;
  t: (key: string) => string;
  option: (value: string) => string;
  lockLabel: (value: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function initialLanguage(): VisionLanguage {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'es') return stored;
  return window.navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function VisionI18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<VisionLanguage>(initialLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => {
    const dictionary = language === 'es' ? es : en;
    return {
      language,
      setLanguage: setLanguageState,
      t: (key) => dictionary[key] ?? en[key] ?? key,
      option: (raw) => language === 'es' ? (optionLabelsEs[raw] ?? raw) : raw,
      lockLabel: (raw) => language === 'es' ? (lockLabelsEs[raw] ?? raw.replace(/([A-Z])/g, ' $1')) : raw.replace(/([A-Z])/g, ' $1'),
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useVisionI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useVisionI18n must be used inside VisionI18nProvider');
  return value;
}
